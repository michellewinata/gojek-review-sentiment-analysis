print("Recall    : {:.4f}".format(recall_score(y_test, y_pred_lr, zero_division=0)))
print("F1-score  : {:.4f}".format(f1_score(y_test, y_pred_lr, zero_division=0)))
print(classification_report(y_test, y_pred_lr, target_names=['negative', 'positive'], zero_division=0))

